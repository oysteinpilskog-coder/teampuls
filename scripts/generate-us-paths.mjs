// Codegen for src/lib/us-paths.ts — pre-projected SVG path data for the
// USA outline using d3-geo's geoAlbersUsa, matching src/lib/us-projection.ts.
//
// Reuses the same Natural Earth 50m admin-0 dump as the Europe codegen so
// the project only fetches one source file. We filter to a single feature
// (United States of America) — at the inset's 320×200 viewBox the country
// outline is more legible than state borders, and a single path keeps the
// generated chunk tiny.
//
// Run: node scripts/generate-us-paths.mjs

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { geoAlbersUsa, geoPath } from 'd3-geo'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const CACHE_DIR = path.join(__dirname, '.cache')
const CACHE_FILE = path.join(CACHE_DIR, 'ne_50m_admin_0_countries.geojson')
const SOURCE_URL =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson'

// Must match src/lib/us-projection.ts.
const MAP_W = 320
const MAP_H = 200

const projection = geoAlbersUsa()
  .scale(380)
  .translate([MAP_W / 2, MAP_H / 2 + 6])

const pathBuilder = geoPath(projection).pointRadius(0)

function roundPath(d) {
  return d.replace(/-?\d+\.\d+/g, s => {
    const n = Number(s)
    return Number.isInteger(n) ? String(n) : n.toFixed(1).replace(/\.0$/, '')
  })
}

async function loadSource() {
  if (fs.existsSync(CACHE_FILE)) {
    const stat = fs.statSync(CACHE_FILE)
    console.log(`Using cached source (${(stat.size / 1024 / 1024).toFixed(1)} MB) at ${CACHE_FILE}`)
    return JSON.parse(fs.readFileSync(CACHE_FILE, 'utf8'))
  }
  console.log(`Fetching ${SOURCE_URL} …`)
  const res = await fetch(SOURCE_URL)
  if (!res.ok) throw new Error(`Fetch failed: ${res.status} ${res.statusText}`)
  const text = await res.text()
  fs.mkdirSync(CACHE_DIR, { recursive: true })
  fs.writeFileSync(CACHE_FILE, text, 'utf8')
  console.log(`Cached ${(text.length / 1024 / 1024).toFixed(1)} MB → ${CACHE_FILE}`)
  return JSON.parse(text)
}

const fc = await loadSource()

const US_NAMES = new Set([
  'United States of America',
  'United States',
  'USA',
])

const usFeature = fc.features.find(f => {
  const props = f.properties ?? {}
  const name = props.NAME ?? props.name ?? props.NAME_LONG ?? props.ADMIN
  return US_NAMES.has(name)
})

if (!usFeature) {
  throw new Error('Could not find USA feature in source GeoJSON')
}

const d = pathBuilder(usFeature)
if (!d) throw new Error('USA path produced empty geometry')
const rounded = roundPath(d)

const header = `// AUTO-GENERATED by scripts/generate-us-paths.mjs
// Source: Natural Earth 50m admin-0 countries (USA only)
// Projection: Albers USA, viewBox 0 0 ${MAP_W} ${MAP_H}
// Must stay in lockstep with src/lib/us-projection.ts.
// DO NOT EDIT — regenerate with \`node scripts/generate-us-paths.mjs\`.

export interface UsPath {
  name: string
  d: string
}

export const US_COUNTRY_PATHS: UsPath[] = [
`

const body = `  { name: ${JSON.stringify('United States')}, d: ${JSON.stringify(rounded)} },`
const out = header + body + '\n]\n'

const outPath = path.join(ROOT, 'src/lib/us-paths.ts')
fs.writeFileSync(outPath, out, 'utf8')

console.log(`Wrote USA outline → ${outPath} (${(out.length / 1024).toFixed(1)} KB)`)
